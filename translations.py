def translate(language, key):
    """Return the requested translation, falling back to English."""
    language_translations = TRANSLATIONS.get(
        language,
        TRANSLATIONS["en"]
    )

    return language_translations.get(
        key,
        TRANSLATIONS["en"].get(key, key)
    )


def translate_dr_level(language, grade):
    """Return the translated DR classification level."""
    selected = DR_TRANSLATIONS.get(
        language,
        DR_TRANSLATIONS["en"]
    )

    return selected["levels"].get(
        grade,
        DR_TRANSLATIONS["en"]["levels"][grade]
    )


def translate_stage(language, value):
    """Translate a verification stage name or message."""
    selected = DR_TRANSLATIONS.get(
        language,
        DR_TRANSLATIONS["en"]
    )

    if value in selected["stages"]:
        return selected["stages"][value]

    if value in selected["messages"]:
        return selected["messages"][value]

    return value
